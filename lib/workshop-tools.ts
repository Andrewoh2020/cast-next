/**
 * Single source of truth for the video tools Cast hands off to.
 *
 * Used by the in-app handoff UI (DownloadModal) and the README inside the
 * exported ZIP — keep the per-tool steps here so the two never drift.
 */

export interface WorkshopTool {
  /** Stable identifier (lowercase, no spaces). */
  slug: 'kling' | 'higgsfield' | 'artlist';
  /** Display name. */
  name: string;
  /** Short tagline shown next to the name in handoff buttons. */
  tagline: string;
  /** URL we open in a new tab when the user clicks the handoff button.
   *  Prefer the tool's image-to-video entry page; fall back to the homepage
   *  if a deep-link path isn't reliable. */
  url: string;
  /** Numbered steps shown both in-modal and inside the ZIP README. Keep
   *  short — these are the same instructions in both surfaces. */
  steps: string[];
  /** Optional path to a logo file under /public/logos/. When the file is
   *  present, the SendToVideoFooter renders <img>; when absent, it falls
   *  back to a brand-colored text-mark card. */
  logo?: string;
  /** Brand accent color (hex). Used for the left edge of the card and the
   *  fallback text-mark when no logo file exists. */
  accent: string;
}

