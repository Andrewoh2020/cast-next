/** Build the README that ships inside the export ZIP. Same steps as the
 *  in-app handoff, so the two can never drift. */
export function buildPackageReadme(opts: {
  characterName: string;
  filenamePrefix: string;
  hasReferenceSheet: boolean;
  outfitCount: number;
  shotCount: number;
}): string {
  const { characterName, filenamePrefix, hasReferenceSheet, outfitCount, shotCount } = opts;
  const toolSections = WORKSHOP_TOOLS.map((t) => {
    const numbered = t.steps.map((s, i) => `${i + 1}. ${s}`).join('\n');
    return `### ${t.name}\n${numbered}\n`;
  }).join('\n');

  return `# ${characterName} — Cast Workshop Package

## Contents
- ${filenamePrefix}-source.jpg — Profile photo (drop this into your video tool)
${hasReferenceSheet ? `- ${filenamePrefix}-reference-sheet.jpg — 4K 8-panel reference sheet (use as visual reference for new angles)\n` : ''}- wardrobe/ — ${outfitCount} outfit variant(s)
- scenes/ — ${shotCount} scene shot(s)

## How to use this package

The profile photo is your primary handoff. Upload it as the starting frame in any
image-to-video tool. The reference sheet is for *you* — keep it open as a visual
guide when writing prompts ("front-facing, three-quarter right, etc.").

${toolSections}
## License
Generated by Cast (castability.ai).
`;
}
